export interface PublicGoodAction {
  id: string;
  categoryId: string;
  categoryName: string;
  text: string;
}

export interface PublicGoodCategory {
  id: string;
  name: string;
  displayName: string;
  number: string;
  actions: PublicGoodAction[];
}

function category(id: string, name: string, number: string, texts: string[], displayName = name): PublicGoodCategory {
  return {
    id, name, displayName, number,
    actions: texts.map((text, index) => ({
      id: `kindness-${id}-${String(index + 1).padStart(2, '0')}`,
      categoryId: id,
      categoryName: displayName,
      text,
    })),
  };
}

